use crate::engine::{extractor::FileFeatures, glossary::Glossary};

pub struct WikiProxy;

impl WikiProxy {
    /// Generates a beautiful Agent-Native Wiki page in Markdown.
    pub fn generate_markdown(
        target_path: &str,
        features: &FileFeatures,
        glossary: &Glossary,
    ) -> String {
        let mut wiki = String::new();
        let title = glossary.aliases.get(target_path).unwrap_or(&target_path.to_string()).clone();

        wiki.push_str(&format!("# 📄 {} \n\n", title));
        wiki.push_str(&format!("**物理路徑**: `{}`\n", target_path));
        wiki.push_str(&format!("**架構角色**: `{}`\n", if features.symbol_count > 10 { "核心樞紐 (HUB)" } else { "葉片節點 (LEAF)" }));
        
        wiki.push_str("\n### 🛠️ 語義特徵張量\n");
        wiki.push_str(&format!("*   **邏輯複雜度**: [{}{}] ({:.2})\n", 
            "█".repeat((features.control_flow_score * 5.0) as usize),
            "░".repeat(5 - (features.control_flow_score * 5.0).min(5.0) as usize),
            features.control_flow_score
        ));

        wiki.push_str("\n### 🔗 物理符號與出口 (SCIP Exports)\n");
        for sym in &features.exports {
            let sym_alias = glossary.aliases.get(&sym.id).unwrap_or(&sym.name);
            wiki.push_str(&format!("*   `{}` (L{})\n", sym_alias, sym.line));
        }
        
        wiki.push_str("\n---\n*Generated by CCAP Reverse Proxy | Local Fidelity Verified*");
        wiki
    }

    /// Wraps markdown into a professional HTML template with CSS.
    pub fn generate_html(markdown_content: &str) -> String {
        let html_template = format!(r#"
<!DOCTYPE html>
<html>
<head>
    <meta charset="utf-8">
    <title>CCAP Semantic Wiki</title>
    <script src="https://cdn.jsdelivr.net/npm/marked/marked.min.js"></script>
    <style>
        body {{ font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif; line-height: 1.6; color: #333; max-width: 900px; margin: 40px auto; padding: 20px; background-color: #f9f9f9; }}
        #content {{ background: white; padding: 40px; border-radius: 12px; box-shadow: 0 4px 20px rgba(0,0,0,0.08); border-left: 8px solid #AEB98F; }}
        h1 {{ color: #2c3e50; border-bottom: 2px solid #eee; padding-bottom: 10px; }}
        code {{ background: #f1f1f1; padding: 2px 6px; border-radius: 4px; font-family: 'Consolas', monospace; color: #d63384; }}
        ul {{ list-style-type: none; padding-left: 0; }}
        li {{ margin-bottom: 10px; padding: 8px; background: #fafafa; border-radius: 6px; }}
        .footer {{ margin-top: 40px; font-size: 0.8em; color: #888; text-align: center; }}
    </style>
</head>
<body>
    <div id="content"></div>
    <div class="footer">CCAP V6.0 | Standards-Based Semantic Engineering</div>
    <script>
        document.getElementById('content').innerHTML = marked.parse(`{}`);
    </script>
</body>
</html>
        "#, markdown_content);
        html_template
    }
}
